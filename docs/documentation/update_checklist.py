#!/usr/bin/env python3
"""Inventory live owned files; ticks require explicit, current review receipts."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "docs/documentation"
RECEIPTS = HERE / "reviews.json"
CHECKLIST = HERE / "file-checklist.md"


def inventory(root):
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=root, check=True, stdout=subprocess.PIPE,
    )
    return sorted({name for name in result.stdout.decode().split("\0")
                   if name and (root / name).is_file()})


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(root, names, receipts):
    lines = ["# File-by-file documentation checklist", "",
             "Generated by `update_checklist.py`; see [review rules](README.md).",
             "Ticks mean an explicit review of this exact file revision, not automatic coverage.", ""]
    entries = []
    complete = 0
    group = None
    for name in names:
        parent = str(Path(name).parent)
        if parent != group:
            entries += ["", f"## {parent}", ""]
            group = parent
        receipt = receipts.get(name)
        valid = bool(receipt and (root / receipt["doc"]).is_file()
                     and receipt["sha256"] == digest(root / name))
        complete += valid
        link = quote("../../" + name, safe="/.")
        label = name.replace("[", "\\[").replace("]", "\\]")
        item = f"- [{'x' if valid else ' '}] [{label}]({link})"
        if receipt:
            doc = quote("../../" + receipt["doc"], safe="/.")
            item += f" — [description]({doc})"
            if not valid:
                item += " — **needs re-review** (source changed or document missing)"
        else:
            item += " — not yet audited"
        entries.append(item)
    lines += [f"**{complete}/{len(names)} current files reviewed.**", *entries, ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--record-review", metavar="FILE")
    parser.add_argument("--doc", help="Existing repository-relative English document")
    args = parser.parse_args()
    names = inventory(ROOT)
    # Include the generated inventory itself on its very first generation.
    names = sorted(set(names) | {CHECKLIST.relative_to(ROOT).as_posix()})
    receipts = json.loads(RECEIPTS.read_text())
    if args.record_review:
        if args.record_review not in names or not (ROOT / args.record_review).is_file():
            parser.error("review target must be an existing inventoried repository file")
        if args.record_review == CHECKLIST.relative_to(ROOT).as_posix():
            parser.error("the self-changing generated checklist cannot have a stable review hash")
        if not args.doc or args.doc not in names or not (ROOT / args.doc).is_file():
            parser.error("--doc must name an existing inventoried repository file")
        receipts[args.record_review] = {"doc": args.doc, "sha256": digest(ROOT / args.record_review)}
        RECEIPTS.write_text(json.dumps(receipts, indent=2, sort_keys=True) + "\n")
    content = render(ROOT, names, receipts)
    if args.check:
        if not CHECKLIST.exists() or CHECKLIST.read_text() != content:
            parser.exit(1, "Documentation checklist is stale; run with --write.\n")
        print("Documentation checklist matches the working tree.")
    else:
        CHECKLIST.write_text(content)
        print(f"Updated {CHECKLIST.relative_to(ROOT)} ({len(names)} files).")


if __name__ == "__main__":
    main()
